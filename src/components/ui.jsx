/* Photo with a calm fallback so the layout holds before images are added. */
export function Photo({ src, alt, className = '', contain = false }) {
  const [failed, setFailed] = useState(false);
  if (failed) {
    return (
      <div
        role="img"
        aria-label={alt}
        className={`flex items-center justify-center bg-sage text-forest/30 ${className}`}
      >
        <PawIcon size={48} />
      </div>
    );
  }
  return (
    <img
      src={src}
      alt={alt}
      onError={() => setFailed(true)}
      className={contain ? `object-contain p-6 mix-blend-multiply ${className}` : `object-cover ${className}`}
    />
  );
}

/* Pick the dog or cat silhouette for a pet from its breed text. */
const CAT_WORDS = /\b(cat|kitten|persian|siamese|tabby|bengal|ragdoll|maine coon|shorthair|longhair|puspin)\b/i;
export const petImage = (breed = '') => (CAT_WORDS.test(breed) ? '/images/cat.jpg' : '/images/dog.jpg');

/* Round pet avatar using the silhouette artwork (white background blends into the tile). */
export function PetAvatar({ breed, className = '' }) {
  return (
    <img
      src={petImage(breed)}
      alt=""
      aria-hidden="true"
      className={`object-contain p-2 mix-blend-multiply ${className}`}
    />
  );
}
